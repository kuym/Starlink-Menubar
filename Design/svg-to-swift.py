#!/usr/bin/env python3
"""Converts the icon master (Design/signal-icon.svg) into Swift path data for the menu bar icon.

Reads each top-level <g id="..."> and the <polygon points> / <path d> (M, L, Z only: the master is all straight
lines) inside it, and writes Sources/StarlinkMenuBar/SignalIconShapes.swift. Run it after editing the SVG:

    python3 Design/svg-to-swift.py
"""
import pathlib, re, xml.etree.ElementTree as ET

root = pathlib.Path(__file__).resolve().parent.parent
svg = ET.parse(root / 'Design/signal-icon.svg').getroot()
ns = '{http://www.w3.org/2000/svg}'
_, _, width, height = (float(v) for v in svg.get('viewBox').split())

def polygon(points):
    nums = [float(v) for v in re.split(r'[\s,]+', points.strip())]
    return [list(zip(nums[0::2], nums[1::2]))]

def path(d):
    subpaths, cur = [], None
    for cmd, args in re.findall(r'([MLZ])([^MLZ]*)', d.upper()):
        nums = [float(v) for v in re.split(r'[\s,]+', args.strip()) if v]
        pts = list(zip(nums[0::2], nums[1::2]))
        if cmd == 'M':
            cur = pts; subpaths.append(cur)
        elif cmd == 'L':
            cur.extend(pts)
        # Z: subpaths are always closed
    return subpaths

def num(v): return ('%.3f' % v).rstrip('0').rstrip('.')

layers = []
for g in svg.findall(f'{ns}g'):
    shapes = []
    for el in g:
        if el.tag == f'{ns}polygon':
            shapes.append((polygon(el.get('points')), False))
        elif el.tag == f'{ns}path':
            shapes.append((path(el.get('d')), el.get('fill-rule') == 'evenodd'))
    layers.append((g.get('id'), float(g.get('opacity', '1')), shapes))

out = ['// Generated by Design/svg-to-swift.py from Design/signal-icon.svg: edit that, not this.', '',
       'import CoreGraphics', '',
       'enum SignalIconShapes {',
       f'    static let size = CGSize(width: {num(width)}, height: {num(height)})', '',
       '    /// Layer id → its opacity (applied to the layer as a whole) and shapes: each a list of closed outlines',
       '    /// (y down), filled even-odd if flagged.',
       '    static let layers: [String: (opacity: CGFloat, shapes: [(outlines: [[CGPoint]], evenOdd: Bool)])] = [']
for id, opacity, shapes in layers:
    out.append(f'        "{id}": ({num(opacity)}, [')
    for outlines, eo in shapes:
        rings = ', '.join('[' + ', '.join(f'CGPoint(x: {num(x)}, y: {num(y)})' for x, y in ring) + ']' for ring in outlines)
        out.append(f'            ([{rings}], {"true" if eo else "false"}),')
    out.append('        ]),')
out += ['    ]', '}', '']
(root / 'Sources/StarlinkMenuBar/SignalIconShapes.swift').write_text('\n'.join(out))
print('wrote', len(layers), 'layers')
